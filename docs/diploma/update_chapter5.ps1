5.6. Работа с количка и създаване на поръчка
Количката е основна функционалност на системата. Тя позволява на клиента да събира избраните продукти преди финално потвърждение на поръчката. При добавяне на пица frontend приложението изпраща информация за продукта, варианта, количеството и персонализациите. При паста се изпраща избраният сос, а при напитка основно продуктът и количеството.

Системата поддържа както гост потребители, така и вписани потребители. За гост потребителите backend приложението използва cart token, чрез който разпознава текущата количка. За вписаните потребители количката може да бъде свързана с потребителския профил. Това позволява по-гъвкава работа и по-добро потребителско преживяване.

В количката клиентът може да прегледа избраните артикули, крайната цена и количествата. При необходимост може да промени количеството или да премахне продукт. Когато поръчката е готова, потребителят преминава към checkout и въвежда необходимите данни за доставка, например телефон и адрес.

След потвърждение frontend приложението изпраща заявка към backend endpoint за приключване на количката. Backend частта проверява дали количката не е празна, дали задължителните данни са попълнени и променя статуса на поръчката. Така временната количка се превръща в реална поръчка.

