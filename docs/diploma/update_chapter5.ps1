$word = New-Object -ComObject Word.Application
$word.Visible = $false
$doc = $null

try {
  $doc = $word.Documents.Open($DocPath)
  $chapter5Matches = @()
  $scan = $doc.Content.Duplicate
  $scan.Find.Text = "5. Ръководство за използване"
  $scan.Find.Forward = $true
  while ($scan.Find.Execute()) {
    $chapter5Matches += [pscustomobject]@{
      Start = [int]$scan.Start
      End = [int]$scan.End
    }
    $scan.Start = $scan.End
    $scan.End = $doc.Content.End
  }
  if ($chapter5Matches.Count -eq 0) {
    throw "Could not find chapter 5 heading."
  }

  $last = $chapter5Matches[$chapter5Matches.Count - 1]
  $findStart = $doc.Range($last.Start, $last.End)

  $findEnd = $doc.Content.Duplicate
  $findEnd.Start = $findStart.End
  $findEnd.Find.Text = "6. Заключение"
  $findEnd.Find.Forward = $true
  if (-not $findEnd.Find.Execute()) {
    throw "Could not find chapter 6 heading."
  }

  $replaceRange = $doc.Range($findStart.Start, $findEnd.Start)
  $replaceRange.Text = $chapterText + "`r"

  $captions = @{
    home = "Фигура 5.1. Начална страница на системата TastyPizza"
    menu = "Фигура 5.2. Страница меню с категории и продукти"
    login = "Фигура 5.3. Форма за вход в системата"
    register = "Фигура 5.4. Форма за регистрация на потребител"
    profile = "Фигура 5.5. Потребителски профил"
    admin = "Фигура 5.6. Административен dashboard и health статус"
  }

  foreach ($key in @("home", "menu", "login", "register", "profile", "admin")) {
    $placeholder = "[SCREENSHOT:$key]"
    $range = $doc.Content.Duplicate
    $range.Find.Text = $placeholder
    $range.Find.Forward = $true
    if ($range.Find.Execute()) {
      $range.Text = ""
      $range.InsertParagraphBefore()
      $imgRange = $doc.Range($range.Start, $range.Start)
      $shape = $doc.InlineShapes.AddPicture($screens[$key], $false, $true, $imgRange)
      $shape.LockAspectRatio = $true
      if ($shape.Width -gt 460) {
        $shape.Width = 460
      }
      $after = $doc.Range($shape.Range.End, $shape.Range.End)
      $after.InsertParagraphAfter()
      $after = $doc.Range($after.End, $after.End)
      $after.Text = $captions[$key] + "`r"
      $after.Style = "Caption"
    }
  }

  $doc.Save()
}
finally {
  if ($doc -ne $null) { $doc.Close($true) | Out-Null }
  $word.Quit() | Out-Null
  [System.Runtime.InteropServices.Marshal]::ReleaseComObject($word) | Out-Null
}

Write-Output "Updated: $DocPath"
Write-Output "Backup: $backupPath"

