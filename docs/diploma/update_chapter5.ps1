Основната цел на началната страница е да ориентира клиента и да го насочи към процеса на поръчка. Потребителят може да избере бутон за директно преминаване към менюто или да разгледа секции с последно добавени продукти. Тези секции позволяват бърз достъп до актуалните пици, пасти и напитки, без да е необходимо клиентът да преминава през цялото меню.

Началната страница използва заявки към backend приложението, за да зареди последните продукти от всяка категория. Така съдържанието не е статично, а се определя от реалните данни в базата. Когато администраторът добави нов продукт, той може да се появи в началната страница според логиката за сортиране.

