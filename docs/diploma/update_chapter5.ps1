Административният dashboard показва обобщена информация за системата. В него се визуализира броят на пиците, пастите, напитките, поръчките и потребителите. Освен това страницата показва health статус на backend API и базата данни. Това е полезно при демонстрация, защото доказва реална връзка между frontend интерфейса и сървърната диагностика.

