5.4. Регистрация и вход в системата
Системата поддържа регистрация и вход на потребители. Регистрацията позволява създаване на нов профил, който след това може да се използва за достъп до лична информация и поръчки. При регистрация потребителят въвежда необходимите данни, а backend приложението валидира заявката и създава запис в базата данни.

При вход потребителят въвежда потребителско име и парола. Backend приложението проверява данните и при успешна автентикация връща JWT token. Frontend приложението съхранява този token и го изпраща при достъп до защитени ресурси. По този начин системата различава гост потребители, регистрирани потребители и администратори.

